from typing import List, Dict, Tuple, Optional, Generator
from google import genai
from google.genai import types, errors
from app.config import (
    reload_env,
    ANSWER_RULES,
    TEMPERATURE,
    GEMMA_MODEL,
)

_cached_client: Optional[genai.Client] = None
_cached_key: Optional[str] = None


def get_client() -> Tuple[Optional[genai.Client], bool]:
    """
    Dynamically returns the initialized Google GenAI client and demo_mode boolean.
    Re-initializes if the API key in .env was modified.
    """
    global _cached_client, _cached_key
    current_key = reload_env()

    if not current_key:
        return None, True

    if _cached_client is not None and _cached_key == current_key:
        return _cached_client, False

    try:
        _cached_client = genai.Client(api_key=current_key)
        _cached_key = current_key
        return _cached_client, False
    except Exception as e:
        print(f"[Warning] Failed to initialize Google GenAI Client: {e}")
        return None, True


def _friendly_error(e: errors.APIError, model_name: str) -> str:
    """Provides human-readable feedback for common Google AI Studio API errors."""
    code = getattr(e, "code", None)
    err_str = str(e).lower()
    if code in (400, 401, 403) and "key" in err_str:
        return "Authentication Error: The GOOGLE_API_KEY was rejected by Google AI Studio. Please verify that your key is active and copied correctly."
    if code == 429:
        return "Rate Limit Exceeded: The Google AI Studio free-tier quota has been temporarily reached. Please wait a minute and retry."
    if code == 404:
        return f"Model Not Found: The model '{model_name}' was not found. Please verify the GEMMA_MODEL setting in your backend/.env file."
    return f"Google GenAI Error: Request to Gemma failed ({e})."


def generate_llm_reply(user_text: str, system_text: str = ANSWER_RULES, demo_reply: str = "") -> Tuple[str, bool]:
    """
    Sends a generation request to Gemma with low temperature.
    Falls back to `demo_reply` if running without an API key.
    Returns (reply_text, is_demo_mode).
    """
    client, is_demo = get_client()
    if is_demo or client is None:
        return demo_reply, True

    import os
    model_name = os.environ.get("GEMMA_MODEL", GEMMA_MODEL).strip() or "gemma-4-26b-a4b-it"

    try:
        response = client.models.generate_content(
            model=model_name,
            contents=user_text,
            config=types.GenerateContentConfig(
                system_instruction=system_text,
                temperature=TEMPERATURE,
            ),
        )
        return (response.text or "").strip(), False
    except errors.APIError as e:
        return _friendly_error(e, model_name), False
    except Exception as e:
        return f"Error connecting to Gemma: {e}", False


def generate_llm_reply_stream(
    user_text: str, system_text: str = ANSWER_RULES, demo_reply: str = ""
) -> Generator[str, None, None]:
    """
    Streams tokens as they are generated by Gemma 4.
    Falls back to yielding `demo_reply` if running in demo mode.
    """
    client, is_demo = get_client()
    if is_demo or client is None:
        # In demo mode, yield chunks of the demo reply with minor delays
        yield demo_reply
        return

    import os
    model_name = os.environ.get("GEMMA_MODEL", GEMMA_MODEL).strip() or "gemma-4-26b-a4b-it"

    try:
        stream = client.models.generate_content_stream(
            model=model_name,
            contents=user_text,
            config=types.GenerateContentConfig(
                system_instruction=system_text,
                temperature=TEMPERATURE,
            ),
        )
        for chunk in stream:
            if chunk.text:
                yield chunk.text
    except errors.APIError as e:
        yield _friendly_error(e, model_name)
    except Exception as e:
        yield f"Error connecting to Gemma: {e}"


def _build_context_and_demo(question: str, retrieved_chunks: List[Dict]) -> Tuple[str, str, bool]:
    """Helper to format prompt context and demo fallback string."""
    client, is_demo = get_client()

    if not retrieved_chunks:
        return (
            "",
            "No campus regulations have been indexed yet. Please upload a regulation PDF or reload the sample syllabus.",
            is_demo,
        )

    context_blocks = [
        f"[{c.get('document', 'Document')} - Page {c['page']}]\n{c['text']}"
        for c in retrieved_chunks
    ]
    context = "\n\n".join(context_blocks)
    prompt = f"Context:\n{context}\n\nQuestion: {question}"

    first = retrieved_chunks[0]
    demo = (
        f"**Demonstration mode:** No GOOGLE_API_KEY is configured in backend/.env, so Gemma did not run live generation. "
        f"Semantic retrieval completed successfully via `all-MiniLM-L6-v2`! "
        f"The most relevant passage is from **{first.get('document', 'Document')} (Page {first['page']})** "
        f"with a similarity score of {first.get('score', 0):.2f}:\n\n"
        f"> \"{first['text'][:350]}...\"\n\n"
        f"*To enable live AI answers with Gemma 4, set your `GOOGLE_API_KEY` in `backend/.env`.*"
    )

    return prompt, demo, is_demo


def answer_question(question: str, retrieved_chunks: List[Dict]) -> Tuple[str, bool]:
    """
    STAGE 4: Formats context including document name and page number,
    prompts Gemma 4 synchronously, and returns (answer_text, is_demo_mode).
    """
    prompt, demo, is_demo = _build_context_and_demo(question, retrieved_chunks)
    if not prompt:
        return demo, is_demo

    reply_text, final_is_demo = generate_llm_reply(user_text=prompt, system_text=ANSWER_RULES, demo_reply=demo)
    return reply_text, final_is_demo


def answer_question_stream(
    question: str, retrieved_chunks: List[Dict]
) -> Tuple[Generator[str, None, None], bool]:
    """
    STAGE 4 (Streaming): Returns a token generator for real-time streaming to the UI.
    Returns (token_generator, is_demo_mode).
    """
    prompt, demo, is_demo = _build_context_and_demo(question, retrieved_chunks)
    if not prompt:
        def empty_gen():
            yield demo
        return empty_gen(), is_demo

    stream_gen = generate_llm_reply_stream(user_text=prompt, system_text=ANSWER_RULES, demo_reply=demo)
    return stream_gen, is_demo
